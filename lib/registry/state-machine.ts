/**
 * Work lifecycle state machine — pure, synchronous, no I/O.
 *
 * Every mutation goes through {@link applyWorkEvent}, so the rules that
 * protect published content live in exactly one place and can be unit
 * tested without a server. The store only persists the result.
 *
 * Invariants enforced here (each has a test):
 *  - `publishedVersionId` only ever points at a version whose status is
 *    `approved` (set by publish, verified by restore).
 *  - Submitting a new version NEVER moves `publishedVersionId`; a link that
 *    already works keeps serving the same bytes until a reviewer publishes.
 *  - Only the owner may submit, and `gameId`/`ownerUserId` are immutable.
 *  - Public readability is derived from `state`, never from "we have bytes".
 */

import {
  isPubliclyReadable,
  type ReviewDecision,
  type ReviewRecord,
  type SubmissionRecord,
  type VersionRecord,
  type WorkRecord,
  type WorkState,
} from "./types";

export type WorkEvent =
  | { type: "submit"; versionId: string; title: string; sceneCount: number; sizeBytes: number; actorUserId: string; noteFromAuthor: string | null }
  | { type: "claim_review"; actorUserId: string }
  | { type: "decide"; decision: ReviewDecision; reasonCodes: string[]; reasonText: string; checklist: Record<string, boolean>; actorUserId: string }
  | { type: "publish"; actorUserId: string }
  | { type: "withdraw"; actorUserId: string }
  | { type: "unlist"; actorUserId: string }
  | { type: "restore"; actorUserId: string }
  | { type: "archive"; actorUserId: string }
  /**
   * Ownership reassignment. Orthogonal to the lifecycle: it never changes
   * `state`, `publishedVersionId` or the version list, only `ownerUserId`.
   * Needed for legacy works imported before accounts existed, and to hand a
   * work back after a mistaken claim.
   */
  | { type: "transfer_owner"; toUserId: string; actorUserId: string };

export type TransitionErrorCode =
  | "not_owner"
  | "game_id_taken"
  | "invalid_state"
  | "version_not_found"
  | "version_not_approved"
  | "no_published_version"
  | "duplicate_version"
  | "reason_required"
  | "work_archived";

export interface TransitionError {
  ok: false;
  code: TransitionErrorCode;
  message: string;
}

export type TransitionResult = { ok: true; work: WorkRecord; changed: boolean } | TransitionError;

export interface TransitionOptions {
  /** ISO timestamp supplied by the caller so the function stays pure. */
  now: string;
  /** Required for `submit`; generated by the caller (crypto.randomUUID). */
  submissionId?: string;
}

function fail(code: TransitionErrorCode, message: string): TransitionError {
  return { ok: false, code, message };
}

function clone(work: WorkRecord): WorkRecord {
  return {
    ...work,
    versions: work.versions.map((v) => ({ ...v })),
    submissions: work.submissions.map((s) => ({ ...s, review: s.review ? { ...s.review } : null })),
  };
}

function settle(work: WorkRecord, now: string): WorkRecord {
  work.updatedAt = now;
  work.revision += 1;
  return work;
}

/** Latest approved-or-superseded version — what a restore may point back at. */
export function findRestorableVersion(work: WorkRecord): VersionRecord | null {
  const published = work.publishedVersionId
    ? work.versions.find((v) => v.versionId === work.publishedVersionId) ?? null
    : null;
  if (published && (published.status === "approved" || published.status === "superseded")) {
    return published;
  }
  // Fall back to the newest version a reviewer ever approved.
  const approved = work.versions.filter(
    (v) => v.status === "approved" || v.status === "superseded",
  );
  return approved.length > 0 ? approved[approved.length - 1] : null;
}

/**
 * True when the work may be created at all: the id is unclaimed, or it is
 * already owned by this actor. Checked by the store before `createWork`.
 */
export function canClaimGameId(existing: WorkRecord | null, actorUserId: string): boolean {
  return existing === null || existing.ownerUserId === actorUserId;
}

/**
 * Apply one event. Returns a NEW work object; the input is never mutated.
 *
 * Callers persist the result only when `ok` and `changed` are both true.
 */
export function applyWorkEvent(
  work: WorkRecord,
  event: WorkEvent,
  opts: TransitionOptions,
): TransitionResult {
  const { now } = opts;

  if (work.state === "archived" && event.type !== "restore" && event.type !== "transfer_owner") {
    return fail("work_archived", "作品已归档，只能先恢复再操作。");
  }

  switch (event.type) {
    case "transfer_owner": {
      // Deliberately narrow: content, lifecycle state and the published
      // pointer are untouched, so a transfer can never change what the public
      // sees. Only who may submit the next version moves.
      if (event.toUserId === work.ownerUserId) {
        return fail("invalid_state", "该用户已经是作品归属人。");
      }
      const next = clone(work);
      next.ownerUserId = event.toUserId;
      return { ok: true, work: settle(next, now), changed: true };
    }

    case "submit":
      return applySubmit(work, event, opts);

    case "claim_review": {
      // Review actions are keyed on the SUBMISSION, not on the work's main
      // state: an already-published work can have a new pending submission,
      // and its live version must stay published throughout that review.
      const pending = [...work.submissions].reverse().find((s) => s.status === "pending");
      if (!pending) {
        return fail("invalid_state", "没有待领取的提交记录。");
      }
      const next = clone(work);
      const target = [...next.submissions].reverse().find((s) => s.status === "pending")!;
      target.status = "in_review";
      target.assignedReviewerId = event.actorUserId;
      if (!isPubliclyReadable(work.state)) next.state = "in_review";
      return { ok: true, work: settle(next, now), changed: true };
    }

    case "decide": {
      const inReview = [...work.submissions].reverse().find((s) => s.status === "in_review");
      if (!inReview) {
        return fail("invalid_state", "没有处于审核中的提交记录。");
      }
      if (event.decision !== "approve" && event.reasonCodes.length === 0) {
        return fail("reason_required", "退回或拒绝必须至少给出一个结构化原因。");
      }
      const next = clone(work);
      const submission = [...next.submissions].reverse().find((s) => s.status === "in_review")!;
      const review: ReviewRecord = {
        reviewerId: event.actorUserId,
        decision: event.decision,
        reasonCodes: [...event.reasonCodes],
        reasonText: event.reasonText,
        checklist: { ...event.checklist },
        decidedAt: now,
      };
      submission.review = review;
      const version = next.versions.find((v) => v.versionId === submission.versionId);
      if (!version) {
        return fail("version_not_found", "提交记录引用的版本不存在。");
      }
      if (event.decision === "approve") {
        submission.status = "approved";
        version.status = "approved";
        // A work that is already live stays live: approving the NEXT version
        // must not unpublish the CURRENT one.
        if (!isPubliclyReadable(work.state)) next.state = "approved";
      } else {
        submission.status = "rejected";
        version.status = "rejected";
        // Same rule in reverse: a rejected update leaves the live version
        // serving players. Only a work that was never live changes state.
        if (!isPubliclyReadable(work.state)) {
          next.state = event.decision === "request_changes" ? "changes_requested" : "rejected";
        }
      }
      return { ok: true, work: settle(next, now), changed: true };
    }

    case "publish": {
      const publishable: WorkState[] = ["approved", "published", "unlisted"];
      if (!publishable.includes(work.state)) {
        return fail("invalid_state", `只有审核通过的作品可以发布，当前 ${work.state}。`);
      }
      const target = resolvePublishTarget(work);
      if (!target) {
        return fail("version_not_approved", "找不到已批准且可发布的版本。");
      }
      const next = clone(work);
      // Previously published version becomes superseded but stays readable.
      if (next.publishedVersionId && next.publishedVersionId !== target.versionId) {
        const previous = next.versions.find((v) => v.versionId === next.publishedVersionId);
        if (previous) previous.status = "superseded";
      }
      const version = next.versions.find((v) => v.versionId === target.versionId)!;
      version.status = "approved";
      version.publishedAt = now;
      next.publishedVersionId = target.versionId;
      next.state = "published";
      return { ok: true, work: settle(next, now), changed: true };
    }

    case "withdraw": {
      if (!isPubliclyReadable(work.state)) {
        return fail("invalid_state", `当前状态 ${work.state} 无可撤下的公开版本。`);
      }
      const next = clone(work);
      next.state = "withdrawn";
      return { ok: true, work: settle(next, now), changed: true };
    }

    case "unlist": {
      if (work.state !== "published") {
        return fail("invalid_state", "只有已发布的作品可以下架到「不列出」。");
      }
      const next = clone(work);
      next.state = "unlisted";
      return { ok: true, work: settle(next, now), changed: true };
    }

    case "restore": {
      if (work.state !== "withdrawn" && work.state !== "unlisted" && work.state !== "archived") {
        return fail("invalid_state", "只有已撤下、已下架或已归档的作品需要恢复。");
      }
      const restorable = findRestorableVersion(work);
      if (!restorable) {
        return fail("no_published_version", "没有可恢复的已批准版本。");
      }
      const next = clone(work);
      next.publishedVersionId = restorable.versionId;
      next.state = "published";
      return { ok: true, work: settle(next, now), changed: true };
    }

    case "archive": {
      if (work.state === "in_review") {
        return fail("invalid_state", "审核中的作品不能被归档，请先完成审核。");
      }
      const next = clone(work);
      next.state = "archived";
      return { ok: true, work: settle(next, now), changed: true };
    }

    default: {
      const exhaustive: never = event;
      return fail("invalid_state", `未知事件 ${String(exhaustive)}`);
    }
  }
}

function applySubmit(
  work: WorkRecord,
  event: Extract<WorkEvent, { type: "submit" }>,
  opts: TransitionOptions,
): TransitionResult {
  if (work.ownerUserId !== event.actorUserId) {
    return fail("game_id_taken", "该作品 id 已被其他作者占用。");
  }
  if (work.versions.some((v) => v.versionId === event.versionId)) {
    // Idempotent re-submission of identical bytes: nothing to record, and
    // re-queueing an already-reviewed version would let an author re-roll
    // the dice until a reviewer approves.
    return fail("duplicate_version", "该版本内容已提交过，未重复创建提交记录。");
  }
  const allowed: WorkState[] = [
    "draft",
    "submitted",
    "changes_requested",
    "approved",
    "rejected",
    "published",
    "unlisted",
    "withdrawn",
  ];
  if (!allowed.includes(work.state)) {
    return fail("invalid_state", `当前状态 ${work.state} 不能提交新版本。`);
  }
  const submissionId = opts.submissionId;
  if (!submissionId) {
    return fail("invalid_state", "内部错误：缺少 submissionId。");
  }

  const next = clone(work);
  next.versions.push({
    versionId: event.versionId,
    title: event.title,
    sceneCount: event.sceneCount,
    sizeBytes: event.sizeBytes,
    submittedBy: event.actorUserId,
    createdAt: opts.now,
    status: "pending",
    publishedAt: null,
  });
  const submission: SubmissionRecord = {
    id: submissionId,
    versionId: event.versionId,
    submittedBy: event.actorUserId,
    submittedAt: opts.now,
    noteFromAuthor: event.noteFromAuthor,
    status: "pending",
    assignedReviewerId: null,
    review: null,
  };
  next.submissions.push(submission);
  next.latestVersionId = event.versionId;
  // A live work stays live while its update waits for review. Anything not yet
  // public moves (back) into the review pipeline.
  if (!isPubliclyReadable(work.state)) next.state = "submitted";
  // Deliberately untouched: publishedVersionId. A new submission must not
  // change what is currently live.
  return { ok: true, work: settle(next, opts.now), changed: true };
}

/** The version a publish would promote: the newest approved version. */
export function resolvePublishTarget(work: WorkRecord): VersionRecord | null {
  if (work.latestVersionId) {
    const latest = work.versions.find((v) => v.versionId === work.latestVersionId);
    if (latest && latest.status === "approved") return latest;
  }
  const approved = work.versions.filter((v) => v.status === "approved");
  return approved.length > 0 ? approved[approved.length - 1] : null;
}

/** Human-readable transition table, rendered by the admin work detail page. */
export function allowedEventsFor(state: WorkState): WorkEvent["type"][] {
  switch (state) {
    case "draft":
      return ["submit", "archive"];
    case "submitted":
      return ["claim_review", "submit", "archive"];
    case "in_review":
      return ["decide"];
    case "changes_requested":
      return ["submit", "archive"];
    case "approved":
      return ["publish", "submit", "archive"];
    case "rejected":
      return ["submit", "archive"];
    case "published":
      return ["unlist", "withdraw", "submit", "archive"];
    case "unlisted":
      return ["restore", "withdraw", "submit", "archive"];
    case "withdrawn":
      return ["restore", "archive"];
    case "archived":
      return ["restore"];
    default:
      return [];
  }
}
